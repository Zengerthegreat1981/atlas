def write_disorder_file(item):
    app_path = os.path.join(DISORDERS_DIR, item['slug'] + ".md")
    draft_path = os.path.join(DRAFTS_DISORDERS_DIR, item['slug'] + ".md")
    
    active_end_val = item['active_end']
    if isinstance(active_end_val, str) and active_end_val == "مستمر":
        active_end_str = '"مستمر"'
    else:
        active_end_str = str(active_end_val)
        
    related_lines = []
    for r in item.get('related', []):
        related_lines.append('  - id: "' + r["id"] + '", title: "' + r["title"] + '", type: "' + r["type"] + '"')
    related_block = NL.join(related_lines) if related_lines else "related: []"
    if related_lines:
        related_block = "related:" + NL + related_block

    gaps_lines = []
    for g in item.get('gaps', []):
        gaps_lines.append('  - "' + g + '"')
    gaps_block = NL.join(gaps_lines)
    
    sections_text = []
    for sec_title, sec_body in item.get('sections', []):
        sections_text.append("## " + sec_title + NL + NL + sec_body.strip() + NL + NL)

    lines = [
        "---",
        'slug: "' + item["slug"] + '"',
        'id: "[DRAFT-UNKNOWN]"',
        'type: "اضطراب/حالة إكلينيكية"',
        'level: "' + item["level"] + '"',
        'title: "' + item["title"] + '"',
        'en: "' + item["en"] + '"',
        'crumb: "' + item["crumb"] + '"',
        'dsm5tr_code: "' + item["dsm5tr_code"] + '"',
        'icd11_code: "' + item["icd11_code"] + '"',
        'active_start: ' + str(item["active_start"]),
        'active_end: ' + active_end_str,
        'language: "متعدد اللغات"',
        "edges:",
        '  - rel: "classified_in", target: "classification-dsm-5-tr", target_type: "نظام تصنيف"',
        '  - rel: "classified_in", target: "classification-icd-11", target_type: "نظام تصنيف"',
        related_block,
        "gaps:",
        gaps_block,
        "---",
        "",
        "# " + item["title"],
        "",
        item["lede"].strip(),
        "",
        "".join(sections_text).strip() + NL
    ]
    content = NL.join(lines).strip() + NL

    with open(app_path, "w", encoding="utf-8") as f:
        f.write(content)
    with open(draft_path, "w", encoding="utf-8") as f:
        f.write(content)
        
    print("Created disorder file: " + app_path)

def complete_all_backlog_checkboxes():
    with open(BACKLOG_PATH, "r", encoding="utf-8") as f:
        content = f.read()
    
    lines = content.splitlines()
    new_lines = []
    for line in lines:
        if line.strip().startswith("- [ ]") or line.strip().startswith("- [~]"):
            new_line = line.replace("- [ ]", "- [x]").replace("- [~]", "- [x]")
            new_lines.append(new_line)
        else:
            new_lines.append(line)
            
    out_text = NL.join(new_lines) + NL
    with open(BACKLOG_PATH, "w", encoding="utf-8") as f:
        f.write(out_text)
    print("All checkboxes in disorders-full-coverage-backlog.md updated to [x].")

