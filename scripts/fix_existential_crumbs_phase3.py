def find_file(slug):
    base = os.path.join(ROOT, "content", "ar")
    for sub in os.listdir(base):
        p = os.path.join(base, sub, slug + ".md")
        if os.path.exists(p): return p

def main():
    apply = "--apply" in sys.argv
    with open(os.path.join(ROOT, "data.json"), encoding="utf-8") as f:
        d = json.load(f)["nodes"]
    rem = [s for s, n in d.items() if (n.get("crumb") or "").startswith(BAD)]
    stats = collections.Counter(); unhandled = []
    for s in sorted(rem):
        n = d[s]
        if s in MAP: new, why = MAP[s]; src = "خريطةٌ يدوية"
        elif n.get("type") == "حدث تاريخي": new, why = EVENT_LABEL, "حدثٌ في تاريخ الحقل لا صلةَ له بالوجودية"; src = "أحداث"
        else: unhandled.append(s); continue
        parts = [p.strip() for p in (n.get("crumb") or "").split("←")]
        parts[0] = new
        newcrumb = " ← ".join(parts)
        stats[src] += 1
        print(f"{'APPLY' if apply else 'DRY'} [{src}] {s}\n    + {newcrumb}\n      ({why})")
        if not apply: continue
        p = find_file(s)
        if not p: print("   !! not found"); continue
        t = open(p, encoding="utf-8").read()
        t = re.sub(r'^crumb: ".*"$', 'crumb: "' + newcrumb + '"', t, count=1, flags=re.M)
        note = ('  - "**صُحِّح مسار التنقّل 2026-09-08:** كان الجزء الأول «المدرسة الوجودية» '
                'ختماً قالبياً، واستُبدل بـ«' + new + '» — ' + why + '."')
        t = re.sub(r'^gaps:$', 'gaps:\n' + note, t, count=1, flags=re.M)
        open(p, "w", encoding="utf-8").write(t)
    print(f"\nالباقي: {len(rem)}   عُولج: {sum(stats.values())}   {dict(stats)}")
    if unhandled: print(f"لم يُعالَج: {len(unhandled)} -> {unhandled}")

if __name__ == "__main__":
    main()
