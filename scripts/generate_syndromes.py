def build_file_content(item):
    lines = []
    lines.append("---")
    lines.append(f'slug: "{item["slug"]}"')
    lines.append('id: "[DRAFT-UNKNOWN]"')
    lines.append('type: "متلازمة"')
    lines.append('part: "psychology"')
    lines.append(f'level: "{item["level"]}"')
    lines.append(f'title: "{item["title"]}"')
    lines.append(f'en: "{item["en"]}"')
    lines.append(f'crumb: "الاضطرابات والمتلازمات ← المتلازمات السريرية ← {item["title"].split(" (")[0]}"')
    lines.append(f'active_start: {item["active_start"]}')
    lines.append('active_end: "مستمر"' if item["active_end"] == "مستمر" else f'active_end: {item["active_end"]}')
    lines.append('language: "متعدد اللغات"')
    lines.append("edges:")
    lines.append('  - rel: "belongs_to", target: "الاضطرابات والمتلازمات الإكلينيكية", target_type: "مدرسة"')
    
    lines.append("related:")
    for rel in item["related"]:
        lines.append(f'  - id: "{rel["id"]}", title: "{rel["title"]}", type: "{rel["type"]}"')
        
    lines.append("gaps:")
    for g in item["gaps"]:
        lines.append(f'  - "{g}"')
    lines.append("---")
    lines.append("")
    lines.append(f'# {item["title"]}')
    lines.append("")
    lines.append(item["lede"])
    lines.append("")
    for heading, text in item["sections"]:
        lines.append(f'## {heading}')
        lines.append("")
        lines.append(text)
        lines.append("")
    lines.append("## اقتباسات مختارة")
    lines.append("")
    lines.append("لا يوجد اقتباس مباشر موثوق متاح.")
    lines.append("")
    return chr(10).join(lines)

out_dir = "content/ar/drafts/syndromes"
