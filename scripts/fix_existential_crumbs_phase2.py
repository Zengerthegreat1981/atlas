def find_file(slug):
    base = os.path.join(ROOT, "content", "ar")
    for sub in os.listdir(base):
        p = os.path.join(base, sub, slug + ".md")
        if os.path.exists(p): return p

def main():
    apply = "--apply" in sys.argv
    with open(os.path.join(ROOT, "data.json"), encoding="utf-8") as f:
        d = json.load(f)["nodes"]

    cohort = set()
    for s, n in d.items():
        if not (n.get("crumb") or "").startswith(BAD): continue
        body = (n.get("lede") or "") + " ".join(x[1] for x in n.get("sections", []))
        if any(w in body for w in EX_WORDS): cohort.add(s)

    def school_of(x):
        for e in d[x].get("edges", []):
            if e[0] == "belongs_to" and e[1] in d and d[e[1]].get("type") in ("مدرسة", "تيار"):
                return e[1]

    def neighbour_school(s):
        nb = [r[0] for r in d[s].get("related", []) if r[0] in d] + \
             [e[1] for e in d[s].get("edges", []) if e[1] in d]
        c = collections.Counter()
        for x in nb:
            if x in cohort: continue          # لا يُستشهد بالحشد على نفسه
            if d[x].get("type") in ("مدرسة", "تيار"): c[x] += 2
            k = school_of(x)
            if k: c[k] += 1
        return max(c, key=c.get) if c else None

    stats = collections.Counter(); changed = 0
    for s in sorted(cohort):
        n = d[s]
        parts = [p.strip() for p in (n.get("crumb") or "").split("←")]
        if len(parts) < 2: continue
        if s in OVERRIDE:
            new, why = OVERRIDE[s]; src = "نقضٌ يدويّ"
        else:
            k = neighbour_school(s)
            a = n.get("active_start")
            if k and k not in EXSCH:
                new = re.sub(r'\s*\(.*?\)\s*$', '', d[k].get("title") or '').strip()
                why = f"جيرةُ العقدة تشير إلى {k}"; src = "جيرة"
            elif isinstance(a, int) and a < 1840:
                new = PART_AR.get(n.get("part"), "الفلسفة")
                why = "سابقٌ للوجودية زمنياً، بلا حكمٍ أخصّ"; src = "حدُّ التاريخ"
            elif k:
                new = EX_BY_PART.get(n.get("part"), "الفلسفة الوجودية")
                why = "الجيرةُ وجودية، ودُقِّق الوسمُ بحسب part"; src = "وجودي مُدقَّق"
            else:
                new = PART_AR.get(n.get("part"), "علم النفس")
                why = "لا جيرةَ ولا حكم"; src = "عامٌّ صادق"
        if os.environ.get("CRUMB_TSV"):
            print(f"{s}\t{d[s].get('type')}\t{new}\t{src}\t{(d[s].get('en') or d[s].get('title') or '')}")
            continue
        if new == parts[0]: continue
        parts[0] = new
        newcrumb = " ← ".join(parts)
        stats[src] += 1; changed += 1
        print(f"{'APPLY' if apply else 'DRY'} [{src}] {s}\n    - {' ← '.join([BAD]+parts[1:])}\n    + {newcrumb}\n      ({why})")
        if not apply: continue
        p = find_file(s)
        if not p: print("   !! not found"); continue
        t = open(p, encoding="utf-8").read()
        t = re.sub(r'^crumb: ".*"$', 'crumb: "' + newcrumb + '"', t, count=1, flags=re.M)
        note = ('  - "**صُحِّح مسار التنقّل 2026-09-08:** كان الجزء الأول «المدرسة الوجودية» '
                'ختماً قالبياً؛ واستُبدل بـ«' + new + '». المصدر: ' + src + ' — ' + why + '. '
                'ولم يُشتقَّ من `belongs_to` لأنّ الحقلَ في هذا الحشد مختومٌ آلياً على '
                '«الوجودية العلاجية» حتى لمدخلاتٍ فلسفيةٍ تسبق الوجودية بقرون."')
        t = re.sub(r'^gaps:$', 'gaps:\n' + note, t, count=1, flags=re.M)
        open(p, "w", encoding="utf-8").write(t)
    print(f"\nالحشد: {len(cohort)}   صُحِّح: {changed}   بحسب المصدر: {dict(stats)}")

if __name__ == "__main__":
    main()
